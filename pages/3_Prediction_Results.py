
import streamlit as st
from pathlib import Path


st.set_page_config(
    page_title="Prediction Results | Clinical XAI",
    layout="wide"
)

# Load shared styling
BASE_DIR = Path(__file__).resolve().parents[1]
CSS_PATH = BASE_DIR / "assets" / "style.css"

if CSS_PATH.exists():
    with open(CSS_PATH, "r", encoding="utf-8") as file:
        st.markdown(
            f"<style>{file.read()}</style>",
            unsafe_allow_html=True
        )


# Sidebar navigation
with st.sidebar:
    st.markdown("## Clinical XAI")
    st.caption("Early Deterioration Detection")
    st.divider()

    st.markdown("**Navigation**")
    st.page_link("app.py", label="Overview")
    st.page_link("pages/2_New_Assessment.py", label="New Assessment")
    st.page_link("pages/3_Prediction_Results.py", label="Prediction Results")
    st.page_link("pages/4_Explainability.py", label="Explainability")
    st.page_link("pages/5_Trends_Research.py", label="Trends & Research")

    st.divider()
    st.caption("Research Prototype | Local Environment")


# Page heading
st.title("Prediction Results")
st.write(
    "Compare the predictions generated by the three trained "
    "temporal machine learning models."
)


# Retrieve latest assessment
results = st.session_state.get("assessment_results")

if results is None:
    st.info(
        "No assessment results are available yet. "
        "Complete a new assessment to view predictions."
    )

    st.page_link(
        "pages/2_New_Assessment.py",
        label="Go to New Assessment"
    )
    st.stop()


probabilities = results["probabilities"]
thresholds = results["thresholds"]
alerts = results["alerts"]


# Overall summary
st.divider()
st.subheader("Model Comparison")

col1, col2, col3 = st.columns(3)

model_details = [
    ("Original XGBoost", "original_xgb", col1),
    ("Clinical-only XGBoost", "clinical_xgb", col2),
    ("Temporal Attention LSTM", "lstm", col3)
]

for label, key, column in model_details:

    probability = probabilities[key]
    threshold = thresholds[key]
    alert = alerts[key]

    with column:
        st.markdown(f"#### {label}")

        st.metric(
            label="Predicted probability",
            value=f"{probability * 100:.2f}%"
        )

        st.progress(
            min(max(float(probability), 0.0), 1.0)
        )

        st.caption(
            f"Saved model threshold: {threshold * 100:.2f}%"
        )

        if alert:
            st.warning("Model threshold crossed")
        else:
            st.success("Below model threshold")


# Detailed comparison
st.divider()
st.subheader("Probability and Threshold Comparison")

st.write(
    "A model alert is generated when its predicted probability "
    "meets or exceeds that model's saved threshold."
)

comparison_data = []

for label, key, _ in model_details:

    comparison_data.append({
        "Model": label,
        "Probability (%)": round(probabilities[key] * 100, 2),
        "Threshold (%)": round(thresholds[key] * 100, 2),
        "Threshold crossed": (
            "Yes" if alerts[key] else "No"
        )
    })

st.dataframe(
    comparison_data,
    use_container_width=True,
    hide_index=True
)


# Interpretation
st.divider()
st.subheader("Interpretation")

alert_count = sum(alerts.values())

if alert_count == 0:
    st.success(
        "None of the three models crossed its saved prediction threshold."
    )

elif alert_count == 3:
    st.warning(
        "All three models crossed their respective prediction thresholds."
    )

else:
    st.warning(
        f"{alert_count} out of 3 models crossed their respective "
        "prediction thresholds. The models do not fully agree."
    )


st.markdown("#### Understanding the three models")

st.markdown(
    """
    - **Original XGBoost:** Uses vital signs, patient context,
      missingness indicators and engineered temporal features.
    - **Clinical-only XGBoost:** Excludes ICU timing context variables
      to examine the contribution of the remaining clinical features.
    - **Temporal Attention LSTM:** Analyses six consecutive hourly
      observations and produces temporal attention weights.
    """
)


# Patient observation summary
observations = st.session_state.get("assessment_observations")

if observations is not None:

    st.divider()
    st.subheader("Assessment Input Summary")

    st.write(
        f"Observations evaluated: **{len(observations)}**"
    )

    if "ICULOS" in observations.columns:
        st.write(
            f"ICU observation hours: "
            f"**{observations['ICULOS'].min()} – "
            f"{observations['ICULOS'].max()}**"
        )

    with st.expander("View submitted observations"):
        st.dataframe(
            observations,
            use_container_width=True,
            hide_index=True
        )


# Important limitations
st.divider()
st.subheader("Important Notes")

st.info(
    """
    These probabilities are outputs from research models and are
    not necessarily calibrated clinical risk estimates.

    Threshold crossing indicates a model alert only. It does not
    establish a diagnosis, determine treatment, or replace clinical
    assessment.

    Results are based on the trained models and the research dataset
    subset used in this project.
    """
)

if st.button("Start New Assessment", type="primary"):
    st.switch_page("pages/2_New_Assessment.py")
